import { expect, test, type Page } from '@playwright/test'

const wish = 'Retrouver le plaisir de dessiner des oiseaux'
const mission = 'Créer un jardin partagé avec mes voisins'
const session = (page: Page) => page.getByRole('region', { name: 'Ma séance avec IAO' })
const birthday = (page: Page) => page.getByLabel('Date de naissance', { exact: true })
const consent = (page: Page) => session(page).getByLabel('J’autorise cet envoi à IAO')
const send = (page: Page) => session(page).getByRole('button', { name: 'Envoyer cette séance à IAO' })
const personalShare = (page: Page) => session(page).getByLabel('Partager mon envie et ma mission avec IAO')
const markerShare = (page: Page) => session(page).getByLabel('Partager le repère natal choisi avec IAO')
const marker = (page: Page) => session(page).getByLabel('Repère de mon thème pour cette séance')
const exactMessage = (page: Page) => session(page).locator('details').filter({
  has: page.getByText('Voir le message exact avant l’envoi', { exact: true }),
})

async function watchChat(page: Page) {
  const prompts: string[] = []
  await page.clock.setFixedTime(new Date('2026-11-25T12:00:00Z'))
  await page.route('**/*', async route => {
    const request = route.request()
    if (request.method() === 'POST') {
      expect(new URL(request.url()).pathname).toBe('/api/chat')
      const { messages } = request.postDataJSON()
      expect(messages).toHaveLength(1)
      expect(messages[0].role).toBe('user')
      prompts.push(messages[0].content)
      return route.fulfill({ contentType: 'text/event-stream', body: 'data: {"text":"Reçu"}\n\ndata: [DONE]\n\n' })
    }
    return new URL(request.url()).origin === 'http://127.0.0.1:51066' ? route.continue() : route.abort()
  })
  await page.goto('/dashboard/cycles')
  return prompts
}

async function compose(page: Page) {
  await session(page).getByRole('button', { name: 'Composer ma séance' }).click()
  await expect(session(page).getByRole('heading', { name: 'Ma séance composée' })).toBeVisible()
  return session(page).getByRole('listitem').allTextContents()
}

async function readPreview(page: Page) {
  const details = exactMessage(page)
  if (!await details.locator('pre').isVisible()) await details.locator('summary').click()
  await expect(details.locator('pre')).toBeVisible()
  return details.locator('pre').innerText()
}

async function calculateChart(page: Page) {
  await birthday(page).fill('2000-01-01')
  await page.getByLabel('Heure de naissance', { exact: true }).fill('13:00')
  await page.getByLabel('Fuseau du lieu de naissance', { exact: true }).fill('Europe/Paris')
  await page.getByLabel('Latitude', { exact: true }).fill('48.86')
  await page.getByLabel('Longitude', { exact: true }).fill('2.35')
  await page.getByRole('button', { name: 'Calculer mon thème natal' }).click()
  await expect(page.getByRole('heading', { name: 'Mon thème natal' })).toBeVisible()
}

test('une envie et une mission personnalisent les consignes pratiques et leur partage correspond au texte prévisualisé', async ({ page }) => {
  const prompts = await watchChat(page)
  const form = session(page)
  const original = await compose(page)
  const wishInput = form.getByLabel('Mon envie du moment')
  const missionInput = form.getByLabel('Ma mission de vie, dans mes mots')
  const outcome = form.getByLabel('Ce que je veux obtenir')
  await wishInput.fill(wish)
  const withWish = await compose(page)
  expect(withWish).not.toEqual(original)
  expect(withWish.join(' ')).toContain(wish)
  await missionInput.fill(mission)
  await outcome.selectOption('action')
  const withMission = await compose(page)
  expect(withMission).not.toEqual(withWish)
  expect(withMission.join(' ')).toContain(mission)
  await expect(consent(page)).toBeDisabled()
  await birthday(page).fill('2000-01-01')
  await expect(form.getByRole('heading', { name: 'Ma séance composée' })).toHaveCount(0)
  await expect(wishInput).toHaveValue(wish)
  await expect(missionInput).toHaveValue(mission)
  await expect(outcome).toHaveValue('action')
  await compose(page)
  await expect(marker(page)).toHaveCount(0)
  expect(prompts).toHaveLength(0)
  await expect(personalShare(page)).not.toBeChecked()
  const anonymousPreview = await readPreview(page)
  expect(anonymousPreview).not.toContain(wish)
  expect(anonymousPreview).not.toContain(mission)
  await consent(page).check()
  await send(page).click()
  await expect.poll(() => prompts.length).toBe(1)
  expect(prompts[0]).toBe(anonymousPreview)
  await personalShare(page).check()
  await expect(consent(page)).not.toBeChecked()
  const personalPreview = await readPreview(page)
  expect(personalPreview).toContain(wish)
  expect(personalPreview).toContain(mission)
  expect(personalPreview).not.toContain('2000-01-01')
  await consent(page).check()
  await send(page).click()
  await expect.poll(() => prompts.length).toBe(2)
  expect(prompts[1]).toBe(personalPreview)
  await expect(consent(page)).not.toBeChecked()
  await personalShare(page).check()
  await consent(page).check()
  await form.getByLabel('Durée en minutes').selectOption('12')
  await expect(send(page)).toHaveCount(0)
  await compose(page)
  await expect(consent(page)).not.toBeChecked()
  await expect(personalShare(page)).not.toBeChecked()
  await birthday(page).fill('2000-02-01')
  await expect(wishInput).toHaveValue('')
  await expect(missionInput).toHaveValue('')
  await expect(outcome).toHaveValue('')
  expect(prompts).toHaveLength(2)
})

test('le Soleil et la Lune calculés produisent des consignes différentes et un repère peut être partagé seul', async ({ page }) => {
  const prompts = await watchChat(page)
  await calculateChart(page)
  const form = session(page)
  const mode = form.getByLabel('Mode de séance')
  await mode.selectOption('mixed')
  await form.getByLabel('Mon envie du moment').fill(wish)
  const baseline = await compose(page)
  await marker(page).selectOption('body:Sun')
  const sun = await compose(page)
  expect(sun).not.toEqual(baseline)
  expect(sun.join(' ')).toMatch(/une étape à construire/i)
  await marker(page).selectOption('body:Moon')
  const moon = await compose(page)
  expect(moon).not.toEqual(sun)
  expect(moon.join(' ')).toMatch(/une évolution en profondeur/i)
  await expect(markerShare(page)).not.toBeChecked()
  await expect(personalShare(page)).not.toBeChecked()
  expect(await readPreview(page)).not.toMatch(/Scorpion|Capricorne/i)
  await consent(page).check()
  await markerShare(page).check()
  await expect(send(page)).toBeDisabled()
  const preview = await readPreview(page)
  expect(preview).toContain('Scorpion')
  expect(preview).not.toContain(wish)
  expect(preview).not.toContain('Capricorne')
  for (const datum of ['2000-01-01', '13:00', 'Europe/Paris', '48.86', '2.35']) expect(preview).not.toContain(datum)
  await consent(page).check()
  await send(page).click()
  await expect.poll(() => prompts.length).toBe(1)
  expect(prompts[0]).toBe(preview)
  await mode.selectOption('practical')
  await expect(marker(page)).toHaveCount(0)
  const practical = await compose(page)
  expect(practical.join(' ')).not.toMatch(/Scorpion|Capricorne|une évolution en profondeur/i)
  await mode.selectOption('mixed')
  await expect(marker(page)).toHaveValue('')
  await marker(page).selectOption('body:Sun')
  await compose(page)
  await markerShare(page).check()
  await consent(page).check()
  await page.getByLabel('Heure de naissance', { exact: true }).fill('14:00')
  await expect(send(page)).toHaveCount(0)
  await compose(page)
  await expect(markerShare(page)).toHaveCount(0)
  await expect(consent(page)).not.toBeChecked()
  expect(prompts).toHaveLength(1)
})

test('le résultat choisi change le travail proposé et la vue d’ensemble permet de vérifier les repères utilisés', async ({ page }) => {
  const prompts = await watchChat(page)
  await calculateChart(page)
  const form = session(page)
  await form.getByLabel('Mode de séance').selectOption('spiritual')
  const workshop = 'organiser un atelier d’entraide'
  await form.getByLabel('Mon envie du moment').fill(workshop)
  const outcome = form.getByLabel('Ce que je veux obtenir')
  const options = ['action', 'draft', 'choice']
  const steps = new Set<string>()
  for (const id of options) {
    await outcome.selectOption(id)
    steps.add((await compose(page)).join('\n'))
    if (id === 'draft') {
      await expect(form.getByRole('heading', { name: 'Invitation à adapter' })).toBeVisible()
      await expect(form.getByText(/^Bonjour ! J’aimerais organiser un atelier d’entraide/)).toContainText('Aimeriez-vous y participer ?')
      expect(await readPreview(page)).not.toContain(workshop)
    }
  }
  expect(steps.size).toBe(options.length)
  await marker(page).selectOption('overview')
  const overview = await compose(page)
  expect(overview.join(' ')).toMatch(/Soleil en Capricorne/i)
  expect(overview.join(' ')).toMatch(/Lune en Scorpion/i)
  await form.getByText('Voir les repères utilisés', { exact: true }).click()
  const basis = form.locator('details').filter({ hasText: 'Voir les repères utilisés' })
  await expect(basis).toContainText('Maison 12')
  await expect(basis).toContainText('Ascendant')
  await markerShare(page).check()
  const preview = await readPreview(page)
  expect(preview).not.toContain('Maison 12')
  expect(preview).not.toContain(workshop)
  expect(prompts).toHaveLength(0)
})

