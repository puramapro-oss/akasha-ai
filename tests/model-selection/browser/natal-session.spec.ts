test('heure estimée : une fourchette remplace le thème précis, puis la séance partage seulement les signes choisis', async ({ page }) => {
  const messages: string[] = []
  await page.route('**/api/chat', async route => {
    messages.push(route.request().postDataJSON().messages.at(-1).content)
    await route.fulfill({ contentType: 'text/event-stream', body: 'data: {"text":"Résumé reçu"}\n\ndata: [DONE]\n\n' })
  })
  await paris(page, '2000-01-01', '13:00')
  const precision = page.getByLabel('Précision de l’heure', { exact: true })
  const useAscendant = page.getByLabel('Utiliser l’ascendant calculé pour mes cycles')
  const sampled = page.getByRole('table', { name: 'Signes observés dans la fourchette' })
  await expect(precision).toHaveValue('0')
  await calculate(page)
  await expect(positions(page)).toBeVisible()
  await useAscendant.check()

  await precision.selectOption('30')
  await expect(positions(page)).toHaveCount(0)
  await expect(useAscendant).toHaveCount(0)
  await calculate(page)
  await expect(natal(page).getByRole('heading', { name: 'Thème avec une heure estimée' })).toBeVisible()
  await expect(sampled.getByRole('row', { name: /Soleil/ })).toContainText('Capricorne')
  await expect(sampled.getByRole('row', { name: /Lune/ })).toContainText('Scorpion')
  await expect(useAscendant).toHaveCount(0)
  await expect(sampled.getByRole('columnheader', { name: 'Maison', exact: true })).toHaveCount(0)

  const form = session(page)
  await form.getByLabel('Mode de séance').selectOption('mixed')
  await form.getByLabel('Astrologie des cycles').check()
  await form.getByRole('button', { name: 'Composer ma séance' }).click()
  await expect(form.getByText(/^Profection annuelle · maison/)).toContainText('ascendant inconnu')
  const attach = form.getByLabel('Joindre ma synthèse natale à cet envoi')
  const consent = form.getByLabel('J’autorise cet envoi à IAO')
  const send = form.getByRole('button', { name: 'Envoyer cette séance à IAO' })
  await expect(attach).not.toBeChecked()
  await consent.check()
  await send.click()
  await expect.poll(() => messages.length).toBe(1)
  expect(messages[0]).not.toMatch(/Synthèse natale choisie|Signes observés/i)
  await attach.check()
  await expect(send).toBeDisabled()
  await consent.check()
  await send.click()
  await expect.poll(() => messages.length).toBe(2)
  expect(messages[1]).toMatch(/estimée|fourchette|échantillon/i)
  expect(messages[1]).toMatch(/Soleil[^\n]*Capricorne/i)
  for (const message of messages) {
    for (const raw of ['2000-01-01', 'Europe/Paris', '13:00', '48.86', '2.35']) expect(message).not.toContain(raw)
  }

  await page.getByLabel('Heure de naissance', { exact: true }).fill('')
  await expect(sampled).toHaveCount(0)
  await expect(form.getByRole('heading', { name: 'Ma séance composée' })).toHaveCount(0)
  await calculate(page)
  await expect(positions(page).getByRole('row')).toHaveCount(3)
  await expect(useAscendant).toHaveCount(0)
  await page.getByLabel('Heure de naissance', { exact: true }).fill('13:00')
  await precision.selectOption('0')
  await calculate(page)
  await expect(positions(page).getByRole('row')).toHaveCount(11)
  await expect(useAscendant).not.toBeChecked()
  await expect(sampled).toHaveCount(0)
})
