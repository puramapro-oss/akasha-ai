test('changer de maisons et de convention recalcule les positions et protège les profections tropicales', async ({ page }) => {
  await paris(page, '2000-01-01', '13:00')
  await calculate(page)
  const sun = positions(page).getByRole('row', { name: /Soleil/ })
  await expect(sun.getByRole('cell').last()).toHaveText('10')
  await page.getByRole('combobox', { name: 'Système de maisons', exact: true }).selectOption('equal')
  await expect(positions(page)).toHaveCount(0)
  await calculate(page)
  await expect(sun.getByRole('cell').last()).toHaveText('9')
  const form = session(page)
  await form.getByLabel('Mode de séance').selectOption('mixed')
  await form.getByLabel('Astrologie des cycles').check()
  for (const [value, name, position] of [
    ['lahiri', 'Lahiri', /Sagittaire · 16°/],
    ['fagan-bradley', 'Fagan', /Sagittaire · 15°/],
  ] as const) {
    await page.getByRole('combobox', { name: 'Zodiaque', exact: true }).selectOption(value)
    await expect(positions(page)).toHaveCount(0)
    await calculate(page)
    await expect(sun).toContainText(position)
    await expect(natal(page).getByText(/^Ascendant calculé ·/)).toBeVisible()
    await expect(page.getByLabel('Utiliser l’ascendant calculé pour mes cycles')).toHaveCount(0)
    await form.getByRole('button', { name: 'Composer ma séance' }).click()
    await form.getByText('Voir la synthèse proposée', { exact: true }).click()
    await expect(form.getByText(/Thème natal géocentrique/)).toContainText(name)
    await expect(form.getByText(/Profection annuelle · maison/)).toContainText(/ascendant inconnu/i)
  }
})

test('calcul adulte et transmission contrôlée avec pratiques, puis révocation par changement des données', async ({ page }) => {
  const prompts: string[] = []
  await page.route('**/api/chat', async route => {
    const body = route.request().postDataJSON()
    prompts.push(body.messages.at(-1).content)
    await route.fulfill({ contentType: 'text/event-stream', body: 'data: {"text":"Réponse locale de contrôle"}\n\ndata: [DONE]\n\n' })
  })
  await paris(page, '2000-01-01', '13:00')
  await calculate(page)
  await expect(positions(page).getByRole('row')).toHaveCount(11)
  await expect(positions(page).getByRole('row', { name: /Soleil/ })).toContainText('Capricorne')
  await expect(positions(page).getByRole('row', { name: /Lune/ })).toContainText('Scorpion')
  await expect(natal(page).getByText(/^Ascendant calculé ·/)).toContainText(/Bélier · 26°/)
  await expect(natal(page).getByText(/^Milieu du ciel ·/)).toContainText(/Capricorne · 11°/)
  await page.getByLabel('Utiliser l’ascendant calculé pour mes cycles').check()
  const form = session(page)
  await form.getByLabel('Mode de séance').selectOption('mixed')
  await form.getByLabel('Astrologie des cycles').check()
  await form.getByLabel('Numérologie JYOTI').check()
  await form.getByText('Choisir mes pratiques', { exact: true }).click()
  await form.getByLabel('Écriture personnelle').check()
  await form.getByRole('button', { name: 'Composer ma séance' }).click()
  await expect(form.getByRole('listitem').filter({ hasText: 'Écris quelques mots' })).toBeVisible()
  const attach = form.getByLabel('Joindre ma synthèse natale à cet envoi')
  const consent = form.getByLabel('J’autorise cet envoi à IAO')
  const send = form.getByRole('button', { name: 'Envoyer cette séance à IAO' })
  await expect(attach).not.toBeChecked()
  await consent.check()
  expect(prompts).toHaveLength(0)
  await send.click()
  await expect.poll(() => prompts.length).toBe(1)
  expect(prompts[0]).not.toMatch(/Milieu du ciel|Soleil.*Capricorne/i)
  await form.getByText('Voir la synthèse proposée', { exact: true }).click()
  const preview = await form.getByText(/^Thème natal géocentrique/).textContent()
  expect(preview).toBeTruthy()
  await attach.check()
  await expect(send).toBeDisabled()
  await consent.check()
  await send.click()
  await expect.poll(() => prompts.length).toBe(2)
  expect(prompts[1]).toMatch(/Soleil.*Capricorne/i)
  expect(prompts[1]).toContain(preview)
  expect(prompts[1]).toMatch(/JYOTI/i)
  expect(prompts[1]).toContain('Écris quelques mots')
  for (const prompt of prompts) {
    for (const raw of ['2000-01-01', '13:00', 'Europe/Paris', '48.86', '2.35']) expect(prompt).not.toContain(raw)
  }
  await page.getByLabel('Heure de naissance', { exact: true }).fill('14:00')
  await expect(positions(page)).toHaveCount(0)
  await expect(form.getByRole('heading', { name: 'Ma séance composée' })).toHaveCount(0)
  await expect(consent).toHaveCount(0)
})

test('recherche de ville locale : homonymes, coordonnées, fuseau et invalidation au changement de lieu', async ({ page }) => {
  const network: { url: string; method: string; body: string | null }[] = []
  page.on('request', req => {
    if (['xhr', 'fetch'].includes(req.resourceType())) {
      network.push({ url: req.url(), method: req.method(), body: req.postData() })
    }
  })
  await page.getByLabel('Date de naissance', { exact: true }).fill('2000-01-01')
  await page.getByLabel('Heure de naissance', { exact: true }).fill('13:00')
  const asset = page.waitForResponse(response => new URL(response.url()).pathname === '/data/natal-places.tsv')
  const open = page.getByRole('button', { name: 'Rechercher une ville' })
  await open.click()
  expect((await asset).status()).toBe(200)
  const search = page.getByRole('textbox', { name: 'Ville de naissance' })
  await search.fill('ma ville confidentielle')
  await search.fill('besancon')
  await page.getByRole('button', { name: /^Besançon · France/ }).click()
  await expect(natal(page).getByText('Lieu choisi · Besançon')).toBeVisible()
  await expect(page.getByLabel('Latitude', { exact: true })).toHaveValue('47.24878')
  await expect(page.getByLabel('Longitude', { exact: true })).toHaveValue('6.01815')
  await expect(page.getByLabel('Fuseau du lieu de naissance', { exact: true })).toHaveValue('Europe/Paris')
  await calculate(page)
  await expect(positions(page)).toBeVisible()
  if (!await search.isVisible()) await open.click()
  await search.fill('paris')
  await expect(page.getByRole('button', { name: /^Paris · France/ })).toBeVisible()
  await page.getByRole('button', { name: /^Paris · États-Unis/ }).first().click()
  await expect(positions(page)).toHaveCount(0)
  await expect(page.getByLabel('Latitude', { exact: true })).toHaveValue('33.66094')
  await expect(page.getByLabel('Longitude', { exact: true })).toHaveValue('-95.55551')
  await expect(page.getByLabel('Fuseau du lieu de naissance', { exact: true })).toHaveValue('America/Chicago')
  await expect(natal(page).getByText('Lieu choisi · Paris')).toBeVisible()
  await page.getByLabel('Latitude', { exact: true }).fill('33.5')
  await expect(natal(page).getByText(/^Lieu choisi/)).toHaveCount(0)
  expect(network).toEqual([{ url: origin + '/data/natal-places.tsv', method: 'GET', body: null }])
})


