import { expect, test, type Page } from '@playwright/test'

const origin = 'http://127.0.0.1:51066'
const session = (page: Page) => page.getByRole('region', { name: 'Ma séance avec IAO' })
const natal = (page: Page) => page.getByRole('region', { name: 'Thème natal', exact: true })
const calculate = (page: Page) => page.getByRole('button', { name: 'Calculer mon thème natal' }).click()
const positions = (page: Page) => page.getByRole('table', { name: 'Positions natales' })

test.beforeEach(async ({ page }) => {
  await page.clock.setFixedTime(new Date('2026-11-25T12:00:00Z'))
  await page.route('**/*', route => new URL(route.request().url()).origin === origin
    ? route.continue() : route.abort())
  await page.goto('/dashboard/cycles')
  await expect(page.getByRole('heading', { name: 'Thème natal', exact: true })).toBeVisible()
})

async function paris(page: Page, date: string, time = '') {
  await page.getByLabel('Date de naissance', { exact: true }).fill(date)
  await page.getByLabel('Fuseau du lieu de naissance', { exact: true }).fill('Europe/Paris')
  await page.getByLabel('Latitude', { exact: true }).fill('48.86')
  await page.getByLabel('Longitude', { exact: true }).fill('2.35')
  await page.getByLabel('Heure de naissance', { exact: true }).fill(time)
}

test('heure inconnue : positions du jour disponibles, ni ascendant calculé ni maison attribuée', async ({ page }) => {
  let posts = 0
  page.on('request', req => { if (req.method() === 'POST') posts++ })
  await paris(page, '2000-01-01')
  await calculate(page)
  await expect(page.getByRole('heading', { name: 'Mon thème natal' })).toBeVisible()
  await expect(positions(page).getByRole('row', { name: /Soleil/ })).toContainText('Capricorne')
  await expect(positions(page).getByRole('row', { name: /Lune/ })).toBeVisible()
  await expect(positions(page).getByRole('columnheader', { name: 'Maison' })).toHaveCount(0)
  await expect(natal(page).getByText(/^Ascendant calculé ·|^Milieu du ciel ·/)).toHaveCount(0)
  await expect(page.getByLabel('Utiliser l’ascendant calculé pour mes cycles')).toHaveCount(0)
  expect(posts).toBe(0)
})

test('heure inexistante au printemps : demande une correction, puis accepte la première heure valide', async ({ page }) => {
  await paris(page, '2024-03-31', '02:30')
  await calculate(page)
  await expect(page.getByRole('alert')).toContainText(/inexistant|n.existe|heure.*saut|avanc/i)
  await expect(positions(page)).toHaveCount(0)
  await page.getByLabel('Heure de naissance', { exact: true }).fill('03:00')
  await calculate(page)
  await expect(positions(page)).toBeVisible()
})

